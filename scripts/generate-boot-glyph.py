#!/usr/bin/env python3
"""Generate the offline QINAN boot word from unmodified Noto CJK contours.

Requires fonttools. The generated SVG is an intermediate source artifact whose
markup is inlined in index.html so the startup animation needs no font/network
request. Font license: public/licenses/Noto-CJK.txt (SIL Open Font License).
Run from any directory; only src/boot-glyph.svg is written.
"""

from pathlib import Path
import argparse
from fontTools.ttLib import TTCollection
from fontTools.pens.svgPathPen import SVGPathPen


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--font",
        default="/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc",
        help="Path to the original Noto Sans CJK Bold TTC",
    )
    args = parser.parse_args()
    collection = TTCollection(args.font)
    font = collection.fonts[0]
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    glyphs = []
    for character, name, offset in [("亲", "qin", 70), ("安", "an", 1120)]:
        pen = SVGPathPen(glyph_set)
        glyph_set[cmap[ord(character)]].draw(pen)
        glyphs.append((name, offset, pen.getCommands()))

    lines = [
        '<svg class="boot-glyph" viewBox="0 0 2200 1100" width="2200" height="1100" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false">',
        '  <!-- Original Noto Sans CJK Bold contours; OFL: /licenses/Noto-CJK.txt. Generated by scripts/generate-boot-glyph.py. -->',
        '  <defs>',
    ]
    for name, _, path in glyphs:
        lines.append(f'    <path id="boot-glyph-{name}" fill-rule="nonzero" d="{path}"/>')

    # Each character has two columns and three rows. Clipping occurs in the
    # original font coordinate system (y points up), before the nested fixed
    # transform. Every edge overlaps by 0.8 font units to avoid antialias seams.
    rows = [(550, 880), (220, 550), (-110, 220)]
    for row, (bottom, top) in enumerate(rows):
        for column in range(2):
            x = column * 500 - 0.4
            lines.append(
                f'    <clipPath id="boot-clip-{row}-{column}" clipPathUnits="userSpaceOnUse">'
                f'<rect x="{x:g}" y="{bottom - 0.4:g}" width="500.8" height="{top - bottom + 0.8:g}"/>'
                '</clipPath>'
            )
    lines.append('  </defs>')

    def full_word(class_name, opacity=None):
        opacity_attribute = f' opacity="{opacity}"' if opacity is not None else ''
        lines.append(f'  <g class="{class_name}"{opacity_attribute}>')
        for name, offset, _ in glyphs:
            lines.append(f'    <use href="#boot-glyph-{name}" transform="translate({offset} 940) scale(1 -1)"/>')
        lines.append('  </g>')

    full_word('boot-ghost')
    for character_index, (name, offset, _) in enumerate(glyphs):
        for row in range(3):
            for column in range(2):
                piece = character_index * 6 + row * 2 + column
                lines.extend([
                    f'  <g class="boot-piece" data-boot-piece="{piece}" data-boot-group="{row}" data-boot-glyph="{name}" data-boot-row="{row}" data-boot-column="{column}">',
                    f'    <g transform="translate({offset} 940) scale(1 -1)" clip-path="url(#boot-clip-{row}-{column})"><use href="#boot-glyph-{name}"/></g>',
                    '  </g>',
                ])
    # Fade in this exact, uncut word only after all pieces reach identity. It
    # eliminates even subpixel clipping boundaries at the final assembled hold.
    full_word('boot-complete-word', 0)
    lines.append('</svg>')

    destination = Path(__file__).resolve().parents[1] / 'src' / 'boot-glyph.svg'
    destination.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    collection.close()
    print(f'Generated {destination} with 12 pieces and 3 readiness groups.')


if __name__ == '__main__':
    main()
